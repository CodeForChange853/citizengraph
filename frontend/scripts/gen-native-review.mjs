// Writes NEEDS-NATIVE-REVIEW.md: every Filipino string and whether a native speaker has verified it.
// Sources: src/i18n/fil.json and the mock API's Filipino sentences in src/api/fixtures.json.
//
//   npm run i18n:review              regenerate the list (verified strings keep their tick)
//   npm run i18n:review -- --accept  record the CURRENT Filipino strings as verified (run it only after
//                                    a person has reviewed them). Saved in src/i18n/fil.verified.json.
// A string is ticked only if it is identical to the verified snapshot, so editing or adding a string
// puts it back on the to-review list.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const url = (p) => new URL(p, import.meta.url);
const read = (p) => JSON.parse(readFileSync(url(p), "utf8"));
const en = read("../src/i18n/en.json");
const fil = read("../src/i18n/fil.json");
const fixtures = read("../src/api/fixtures.json");
const VERIFIED = "../src/i18n/fil.verified.json";

function flatten(obj, prefix = "") {
  return Object.entries(obj).flatMap(([k, v]) =>
    typeof v === "object" ? flatten(v, `${prefix}${k}.`) : [[`${prefix}${k}`, v]],
  );
}

const screen = flatten(fil);
const api = Object.entries(fixtures.text.fil).map(([k, v]) => [`api.${k}`, v]);
const current = Object.fromEntries([...screen, ...api]);

if (process.argv.includes("--accept")) {
  writeFileSync(url(VERIFIED), JSON.stringify({ strings: current }, null, 2) + "\n");
  console.log(`fil.verified.json: ${Object.keys(current).length} strings recorded as verified`);
}
const verified = existsSync(url(VERIFIED)) ? read(VERIFIED).strings : {};

const esc = (s) => String(s).replaceAll("|", "&#124;").replaceAll("\n", " ");
const tick = (k, v) => (verified[k] === v ? "✓" : "");
const rows = (pairs, enMap, prefix = "") =>
  pairs
    .map(([k, v]) => `| \`${k}\` | ${esc(enMap.get(k.slice(prefix.length)) ?? "")} | ${esc(v)} | ${tick(k, v)} |`)
    .join("\n");

const enMap = new Map(flatten(en));
const enText = new Map(Object.entries(fixtures.text.en));
const done = Object.entries(current).filter(([k, v]) => verified[k] === v).length;
const total = Object.keys(current).length;

const md = `# Filipino strings and their review status

GENERATED by \`npm run i18n:review\`. Do not edit by hand: fix the string in the source file, then regenerate.
**${done} of ${total} strings verified.** A tick means the string is identical to the snapshot in
\`src/i18n/fil.verified.json\`, recorded with \`npm run i18n:review -- --accept\` after a person reviewed the list.
An empty last column means new or changed since then: it needs review again before it is treated as correct.
Waray is out of scope. Retrieved charter facts (requirements, steps, fees, office names) are in the charter's
own English wording in both languages and are not translated.

## Screen text (\`src/i18n/fil.json\`)

| Key | English | Filipino | Verified |
|---|---|---|---|
${rows(screen, enMap)}

## Sentences from the mock API (\`src/citizengraph/api/main.py\`, \`_TEXT["fil"]\`; keys start with \`api.\`)

| Key | English | Filipino | Verified |
|---|---|---|---|
${rows(api, enText, "api.")}
`;
writeFileSync(url("../NEEDS-NATIVE-REVIEW.md"), md);
console.log(`NEEDS-NATIVE-REVIEW.md: ${done} of ${total} verified`);
