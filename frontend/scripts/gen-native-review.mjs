// Writes NEEDS-NATIVE-REVIEW.md: every Filipino string, unverified until a native speaker reviews it.
// Sources: src/i18n/fil.json and the mock API's Filipino sentences in src/api/fixtures.json.
import { readFileSync, writeFileSync } from "node:fs";

const read = (p) => JSON.parse(readFileSync(new URL(p, import.meta.url), "utf8"));
const en = read("../src/i18n/en.json");
const fil = read("../src/i18n/fil.json");
const fixtures = read("../src/api/fixtures.json");

function flatten(obj, prefix = "") {
  return Object.entries(obj).flatMap(([k, v]) =>
    typeof v === "object" ? flatten(v, `${prefix}${k}.`) : [[`${prefix}${k}`, v]],
  );
}
const esc = (s) => String(s).replaceAll("|", "&#124;").replaceAll("\n", " ");
const rows = (pairs, enMap) =>
  pairs.map(([k, v]) => `| \`${k}\` | ${esc(enMap.get(k) ?? "")} | ${esc(v)} | |`).join("\n");

const enMap = new Map(flatten(en));
const enText = new Map(Object.entries(fixtures.text.en));

const md = `# Filipino strings that need a native speaker

GENERATED by \`npm run i18n:review\`. Do not edit by hand: fix the string in the source file, then regenerate.
Every string below is **unverified**. Do not treat it as correct until a native speaker has ticked the last column.
Waray is out of scope. Retrieved charter facts (requirements, steps, fees, office names) are in the charter's
own English wording in both languages and are not translated.

## Screen text (\`src/i18n/fil.json\`)

| Key | English | Filipino | Reviewed |
|---|---|---|---|
${rows(flatten(fil), enMap)}

## Sentences from the mock API (\`src/citizengraph/api/main.py\`, \`_TEXT["fil"]\`)

| Key | English | Filipino | Reviewed |
|---|---|---|---|
${rows(Object.entries(fixtures.text.fil), enText)}
`;
writeFileSync(new URL("../NEEDS-NATIVE-REVIEW.md", import.meta.url), md);
console.log(`NEEDS-NATIVE-REVIEW.md: ${flatten(fil).length + Object.keys(fixtures.text.fil).length} strings`);
